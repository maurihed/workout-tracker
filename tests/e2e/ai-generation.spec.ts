import { expect, test } from "@playwright/test"
import { PrismaPg } from "@prisma/adapter-pg"

import { PrismaClient } from "../../src/generated/prisma/client"
import {
  cleanupTestUser,
  createTestSession,
  disconnectTestDb,
} from "./helpers/session"
import { AI_MOCK_MODEL, AI_MOCK_ROUTINE } from "./helpers/ai-mock-server"

const prisma = new PrismaClient({
  adapter: new PrismaPg({ connectionString: process.env.DATABASE_URL }),
})

const email = `e2e_ai_${Date.now()}@e2e-test.local`

const SQUAT_SOURCE_ID = AI_MOCK_ROUTINE.days[0].exercises[0].sourceId

/**
 * Seeds one completed session for `userId` with a working set that matches the
 * mock routine's squat entry (`reps: "8-12"`), so personalization raises the
 * starting load deterministically: 100 kg × 1.05 → 105 kg. Returns the catalog
 * exercise id so the spec can assert the accepted routine's target weight.
 */
async function seedSquatHistory(userId: string) {
  const exercise = await prisma.exercise.findFirstOrThrow({
    where: { sourceId: SQUAT_SOURCE_ID },
    select: { id: true },
  })
  const completedAt = new Date(Date.now() - 24 * 60 * 60 * 1000)
  const startedAt = new Date(completedAt.getTime() - 60 * 60 * 1000)
  await prisma.workoutSession.create({
    data: {
      userId,
      name: "Seeded squat session",
      status: "completed",
      startedAt,
      completedAt,
      snapshot: {},
      exercises: {
        create: {
          exerciseId: exercise.id,
          order: 0,
          nameSnapshot: "Barbell Full Squat",
          completed: true,
          sets: {
            create: {
              setNumber: 1,
              type: "working",
              weightKg: 100,
              reps: 12,
              completedAt,
            },
          },
        },
      },
    },
  })
  return exercise.id
}

test.afterAll(async () => {
  await cleanupTestUser(email)
  await disconnectTestDb()
  await prisma.$disconnect()
})

test.skip(
  process.env.AI_E2E !== "1",
  "set AI_E2E=1 to run with the mock provider + worker",
)

/**
 * Manual run (from the repo root, with the Docker db up and seeded):
 *
 *   export PATH="/Applications/Docker.app/Contents/Resources/bin:$PATH"
 *   docker compose up -d db && pnpm db:seed
 *   AI_E2E=1 pnpm e2e -- tests/e2e/ai-generation.spec.ts
 *
 * `AI_E2E=1` makes `playwright.config.ts` wire the gated global setup/teardown
 * that starts the OpenAI-compatible mock provider on 127.0.0.1:4010 and spawns
 * `scripts/worker-ai.ts` against it.
 */
test("generates a routine with the mocked provider, previews and accepts it", async ({
  page,
  context,
}) => {
  test.setTimeout(120_000)

  const { cookie, userId } = await createTestSession(email, { onboarded: true })
  await context.addCookies([{ ...cookie, domain: "127.0.0.1", path: "/" }])

  const squatExerciseId = await seedSquatHistory(userId)

  await page.goto("/en/routines/generate")
  await expect(
    page.getByRole("heading", { name: "Generate a routine with AI" }),
  ).toBeVisible()

  await page.getByLabel("Goal", { exact: true }).selectOption("build_muscle")
  await page
    .getByLabel("Experience", { exact: true })
    .selectOption("beginner")
  await page.getByLabel("Days per week", { exact: true }).selectOption("3")

  await page.getByRole("button", { name: "Generate routine" }).click()

  const accept = page.getByRole("button", { name: "Accept & save" })
  await expect(accept).toBeVisible({ timeout: 60_000 })
  await expect(
    page.getByText(`Generated by AI (${AI_MOCK_MODEL})`),
  ).toBeVisible()
  await expect(
    page.getByText(AI_MOCK_ROUTINE.days[0].exercises[0].name),
  ).toBeVisible()
  await expect(page.getByText("Tuned to your last 3 sessions")).toBeVisible()

  await expect
    .poll(
      async () => {
        const job = await prisma.aiJob.findFirst({
          where: { userId, status: "succeeded" },
          orderBy: { createdAt: "desc" },
          select: { result: true },
        })
        const result = job?.result as {
          personalized?: boolean
          routine?: {
            days?: {
              exercises?: { exerciseId?: string | null; targetWeightKg?: number | null }[]
            }[]
          }
        } | null
        const squat = result?.routine?.days?.[0]?.exercises?.find(
          (exercise) => exercise.exerciseId === squatExerciseId,
        )
        return { personalized: result?.personalized, weight: squat?.targetWeightKg }
      },
      { timeout: 15_000 },
    )
    .toEqual({ personalized: true, weight: 105 })

  await accept.click()

  await expect(page).toHaveURL(/\/en\/routines\/[^/]+$/)

  await expect
    .poll(
      async () => {
        const routine = await prisma.routine.findFirst({
          where: { userId, source: "ai" },
          select: { id: true },
        })
        return routine?.id ?? null
      },
      { timeout: 15_000 },
    )
    .not.toBeNull()

  await expect
    .poll(
      async () => {
        const exercise = await prisma.routineExercise.findFirst({
          where: {
            exerciseId: squatExerciseId,
            routineDay: { routine: { userId, source: "ai" } },
          },
          select: { targetWeightKg: true },
        })
        return exercise?.targetWeightKg ?? null
      },
      { timeout: 15_000 },
    )
    .toBe(105)

  await page.goto("/en/routines")
  await expect(page.getByText(AI_MOCK_ROUTINE.name)).toBeVisible()
  await expect(page.getByText("AI generated", { exact: true })).toBeVisible()
})
