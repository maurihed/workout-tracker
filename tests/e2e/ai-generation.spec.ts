import { expect, test } from "@playwright/test"
import { PrismaPg } from "@prisma/adapter-pg"

import { PrismaClient } from "../../src/generated/prisma/client"
import {
  cleanupTestUser,
  createTestSession,
  disconnectTestDb,
} from "./helpers/session"
import { AI_MOCK_MODEL, AI_MOCK_ROUTINE } from "./helpers/ai-mock-server"

const prisma = new PrismaClient({
  adapter: new PrismaPg({ connectionString: process.env.DATABASE_URL }),
})

const email = `e2e_ai_${Date.now()}@e2e-test.local`

test.afterAll(async () => {
  await cleanupTestUser(email)
  await disconnectTestDb()
  await prisma.$disconnect()
})

test.skip(
  process.env.AI_E2E !== "1",
  "set AI_E2E=1 to run with the mock provider + worker",
)

/**
 * Manual run (from the repo root, with the Docker db up and seeded):
 *
 *   export PATH="/Applications/Docker.app/Contents/Resources/bin:$PATH"
 *   docker compose up -d db && pnpm db:seed
 *   AI_E2E=1 pnpm e2e -- tests/e2e/ai-generation.spec.ts
 *
 * `AI_E2E=1` makes `playwright.config.ts` wire the gated global setup/teardown
 * that starts the OpenAI-compatible mock provider on 127.0.0.1:4010 and spawns
 * `scripts/worker-ai.ts` against it.
 */
test("generates a routine with the mocked provider, previews and accepts it", async ({
  page,
  context,
}) => {
  test.setTimeout(120_000)

  const { cookie, userId } = await createTestSession(email, { onboarded: true })
  await context.addCookies([{ ...cookie, domain: "127.0.0.1", path: "/" }])

  await page.goto("/en/routines/generate")
  await expect(
    page.getByRole("heading", { name: "Generate a routine with AI" }),
  ).toBeVisible()

  await page.getByLabel("Goal", { exact: true }).selectOption("build_muscle")
  await page
    .getByLabel("Experience", { exact: true })
    .selectOption("beginner")
  await page.getByLabel("Days per week", { exact: true }).selectOption("3")

  await page.getByRole("button", { name: "Generate routine" }).click()

  const accept = page.getByRole("button", { name: "Accept & save" })
  await expect(accept).toBeVisible({ timeout: 60_000 })
  await expect(
    page.getByText(`Generated by AI (${AI_MOCK_MODEL})`),
  ).toBeVisible()
  await expect(
    page.getByText(AI_MOCK_ROUTINE.days[0].exercises[0].name),
  ).toBeVisible()

  await accept.click()

  await expect(page).toHaveURL(/\/en\/routines\/[^/]+$/)

  await expect
    .poll(
      async () => {
        const routine = await prisma.routine.findFirst({
          where: { userId, source: "ai" },
          select: { id: true },
        })
        return routine?.id ?? null
      },
      { timeout: 15_000 },
    )
    .not.toBeNull()

  await page.goto("/en/routines")
  await expect(page.getByText(AI_MOCK_ROUTINE.name)).toBeVisible()
  await expect(page.getByText("AI generated", { exact: true })).toBeVisible()
})
